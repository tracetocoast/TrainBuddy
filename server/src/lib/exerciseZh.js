const SORTED_PHRASES = PHRASES.slice().sort((a, b) => b[0].length - a[0].length)

function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function phrasePattern(en) {
  const escaped = escapeRegExp(en).replace(/ /g, '\\s+')
  if (/^[A-Za-z0-9]/.test(en) && /[A-Za-z0-9]$/.test(en)) {
    return new RegExp('\\b' + escaped + '\\b', 'gi')
  }
  return new RegExp(escaped, 'gi')
}

function applyPhrases(text, forInstruction) {
  let out = String(text || '')
  SORTED_PHRASES.forEach(([en, zh]) => {
    if (forInstruction && en.indexOf(' ') < 0 && en.length < 14) return
    out = out.replace(phrasePattern(en), zh)
  })
  return out
}

function applyWords(text) {
  return String(text || '').replace(/[A-Za-z']+/g, (word) => {
    const key = word.toLowerCase()
    if (Object.prototype.hasOwnProperty.call(WORDS, key)) return WORDS[key]
    return word
  })
}

function tidyChinese(text) {
  return String(text || '')
    .replace(/提示：/g, '提示：')
    .replace(/\s+/g, ' ')
    .replace(/([\u4e00-\u9fff])\s+([\u4e00-\u9fff])/g, '$1$2')
    .replace(/([\u4e00-\u9fff])\s+([，。；：！、])/g, '$1$2')
    .replace(/([，。；：！、])\s+/g, '$1')
    .replace(/\s+([\u4e00-\u9fff])/g, '$1')
    .replace(/([\u4e00-\u9fff])\s+/g, '$1')
    .replace(/^[，。；、]+/, '')
    .trim()
}

