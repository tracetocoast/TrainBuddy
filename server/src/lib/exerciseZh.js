const nameCache = new Map()
const instructionCache = new Map()

function translateName(name) {
  if (nameCache.has(name)) return nameCache.get(name)
  const translated = NAME_OVERRIDES[name] || NAME_EXTRAS[name] || tidyChinese(applyWords(applyPhrases(name))) || name
  nameCache.set(name, translated)
  return translated
}

function applyInstructionWords(text) {
  const skip = { the: 1, a: 1, an: 1, of: 1, for: 1, to: 1, that: 1, this: 1, will: 1, be: 1, is: 1, are: 1, as: 1, at: 1, or: 1, if: 1, not: 1, by: 1, than: 1, and: 1, with: 1, from: 1, into: 1, onto: 1 }
  return String(text || '').replace(/[A-Za-z']+/g, (word) => {
    const key = word.toLowerCase()
    if (skip[key]) return word
    if (Object.prototype.hasOwnProperty.call(WORDS, key)) return WORDS[key]
    return word
  })
}

function translateInstruction(text) {
  const raw = String(text || '').replace(/^Tip:\s*/i, '提示：')
  if (instructionCache.has(raw)) return instructionCache.get(raw)
  const translated = tidyChinese(applyInstructionWords(applyPhrases(raw, true))) || raw
  instructionCache.set(raw, translated)
  return translated
}

function translateInstructions(list) {
  return (list || []).map(translateInstruction).filter(Boolean)
}

function targetLabel(value) {
  return TARGET_LABELS[value] || value || ''
}

